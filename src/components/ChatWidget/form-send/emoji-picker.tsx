const RECENT_STORAGE_KEY = "mimin-recent-emojis";

interface EmojiPickerProps {
  isOpen: boolean;
  onClose: () => void;
  onEmojiSelect: (emoji: string) => void;
}

export default function EmojiPicker({
  isOpen,
  onClose,
  onEmojiSelect,
}: EmojiPickerProps) {
  const [selectedCategory, setSelectedCategory] = useState<string>("people");
  const [recentEmojis, setRecentEmojis] = useState<string[]>([]);

  useEffect(() => {
    try {
      const saved = localStorage.getItem(RECENT_STORAGE_KEY);
      if (saved) {
        const parsed = JSON.parse(saved);
        if (Array.isArray(parsed)) {
          setRecentEmojis(parsed.slice(0, 100));
          EMOJI_DATA.recent = parsed.slice(0, 100);
        }
      }
    } catch {
      // ignore
    }
  }, []);

  if (!isOpen) return null;

  const handleEmojiClick = (emoji: string) => {
    onEmojiSelect(emoji);

    const updated = [emoji, ...recentEmojis.filter((e) => e !== emoji)].slice(
      0,
      100
    );
    setRecentEmojis(updated);
    EMOJI_DATA.recent = updated;
    try {
      localStorage.setItem(RECENT_STORAGE_KEY, JSON.stringify(updated));
    } catch {
      // ignore
    }
  };

  const currentEmojis =
    selectedCategory === "recent"
      ? recentEmojis
      : EMOJI_DATA[selectedCategory] || [];

  return (
    <div
      data-emoji-picker
      className="mimin:absolute mimin:bottom-22 mimin:left-0 mimin:mb-2 mimin:w-[320px] mimin:bg-white mimin:border mimin:border-gray-200 mimin:rounded-lg mimin:shadow-xl mimin:z-50"
    >
      <div className="mimin:flex mimin:gap-0.5 mimin:p-1.5 mimin:border-b mimin:border-gray-200 mimin:overflow-x-auto">
        {CATEGORIES.map((cat) => (
          <button
            key={cat.id}
            type="button"
            className={cn(
              "mimin:w-8 mimin:h-8 mimin:shrink-0 mimin:flex mimin:items-center mimin:justify-center mimin:rounded-md mimin:text-base mimin:hover:bg-gray-100 mimin:transition-colors",
              selectedCategory === cat.id &&
                "mimin:bg-gray-100 mimin:ring-1 mimin:ring-gray-300"
            )}
            onClick={() => setSelectedCategory(cat.id)}
            title={cat.name}
          >
            {cat.label}
          </button>
        ))}
      </div>

      <div className="mimin:p-2 mimin:max-h-[300px] mimin:min-h-[300px] mimin:overflow-y-auto">
        {currentEmojis.length === 0 ? (
          <p className="mimin:text-xs mimin:text-center mimin:text-gray-500 mimin:py-6">
            {selectedCategory === "recent"
              ? "No recent emojis"
              : "No emojis found"}
          </p>
        ) : (
          <div className="mimin:grid mimin:grid-cols-8 mimin:gap-0.5">
            {currentEmojis.map((emoji, index) => (
              <button
                key={`${emoji}-${index}`}
                type="button"
                className="mimin:w-8 mimin:h-8 mimin:flex mimin:items-center mimin:justify-center mimin:rounded-md mimin:text-lg mimin:hover:bg-gray-100 mimin:transition-colors"
                onClick={() => handleEmojiClick(emoji)}
              >
                {emoji}
              </button>
            ))}
          </div>
        )}
      </div>
    </div>
  );
}
